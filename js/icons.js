    goldstatue: () => { k *= 2; face(2.5, 1.5, GOLD); k /= 2; R(18, 1, 1, 5, WHITE); R(16, 3, 5, 1, WHITE); B(3, 18, 18, 5, '#8a5a1a'); },
    trophy: () => { R(3, 4, 3, 6, '#f2c14e'); R(18, 4, 3, 6, '#f2c14e'); B(6, 2, 12, 11, GOLD); R(8, 4, 2, 6, WHITE); R(11, 13, 2, 5, '#f2c14e'); B(6, 17, 12, 6, '#8a6a4a'); },
    arcadeset: () => { B(5, 1, 14, 22, RED); R(7, 2, 10, 2, GOLD); B(7, 5, 10, 8, '#14324d'); R(10, 8, 4, 3, '#7ccf6a'); R(6, 14, 12, 3, '#a52c43'); R(8, 12, 1, 3, INK); R(7, 11, 3, 2, GOLD); R(13, 14, 2, 1, WHITE); R(15, 15, 2, 1, WHITE); },
